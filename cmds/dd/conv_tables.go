// ebcdicSpace is the EBCDIC codepoint for <space>. It is used to construct
// fixed-width EBCDIC input records in tests. POSIX conv=sync itself appends
// literal <space> input bytes; those bytes are subsequently translated like
// every other byte when conv=ascii is also active.
const ebcdicSpace = 0x40

// translateBytes applies a 256-entry byte substitution table in place.
func translateBytes(p []byte, table *[256]byte) {
	for i, c := range p {
		p[i] = table[c]
	}
}
